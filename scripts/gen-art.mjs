// Generates lib/art.ts from the Iconify JSON packages in node_modules.
// Sources: @iconify-json/game-icons (game-icons.net, CC BY 3.0) for species silhouettes,
// @iconify-json/ph (Phosphor Icons, MIT) for the few UI icons. Run: npm run art
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (set) => JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json', set, 'icons.json'), 'utf8'));
const game = load('game-icons');
const ph = load('ph');

// One entry per species_kind enum value (supabase/migrations/20261127000000_init.sql, lib/types.ts).
const SPECIES = {
  cat: 'cat',
  dog: 'sitting-dog',
  rabbit: 'rabbit',
  rodent: 'rat',
  bird: 'parrot-head',
  reptile: 'gecko',
  fish: 'tropical-fish',
  other: 'paw-print',
};

// Regular-weight Phosphor icons, only where they label a control.
const UI = ['house', 'file-text'];

// Body + size, so React can draw each one as a mask over currentColor.
function entry(set, name) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`missing icon: ${name}`);
  return `{ body: ${JSON.stringify(icon.body)}, w: ${icon.width ?? set.width}, h: ${icon.height ?? set.height} }`;
}

const speciesLines = Object.entries(SPECIES).map(([kind, name]) => `  ${JSON.stringify(kind)}: ${entry(game, name)},`);
const uiLines = UI.map((name) => `  ${JSON.stringify(name)}: ${entry(ph, name)},`);

const out = `// GENERATED by scripts/gen-art.mjs. Do not edit by hand; run \`npm run art\`.
//
// Pet silhouettes: game-icons.net, CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/), by Lorc, Delapouite and contributors.
// UI icons: Phosphor Icons, MIT (https://github.com/phosphor-icons/core/blob/main/LICENSE).

/** Single-colour species silhouettes, one per species_kind. Drawn as a mask so they take currentColor. */
export const SPECIES_ART: Record<string, { body: string; w: number; h: number }> = {
${speciesLines.join('\n')}
};

/** Phosphor icons as raw SVG body, drawn the same way. */
export const ICONS: Record<string, { body: string; w: number; h: number }> = {
${uiLines.join('\n')}
};
`;

writeFileSync(join(root, 'lib/art.ts'), out);
console.log(`wrote lib/art.ts (${out.length} chars): species=${Object.values(SPECIES).join(', ')}; ui=${UI.join(', ')}`);
