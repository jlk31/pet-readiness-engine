// Generates lib/art.ts from the Iconify JSON packages in node_modules.
// Sources (both MIT): @iconify-json/fluent-emoji (Microsoft Fluent Emoji),
// @iconify-json/ph (Phosphor Icons). Run: npm run art
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (set) => JSON.parse(readFileSync(join(root, 'node_modules/@iconify-json', set, 'icons.json'), 'utf8'));
const emoji = load('fluent-emoji');
const ph = load('ph');

// One entry per species_kind enum value (supabase/migrations/20261127000000_init.sql, lib/types.ts).
const SPECIES = {
  cat: 'cat-face',
  dog: 'dog-face',
  rabbit: 'rabbit-face',
  rodent: 'hamster',
  bird: 'bird',
  reptile: 'lizard',
  fish: 'tropical-fish',
  other: 'paw-prints',
};

// Phosphor duotone icons, returned as raw body + size so React can inline them with currentColor.
const UI = ['house', 'clock', 'wallet', 'heart', 'first-aid', 'map-pin', 'paw-print', 'chart-line-up', 'file-text', 'sun', 'moon'];

// Build a full SVG for an Iconify icon, honouring its set-level / icon-level viewBox fields.
function fullSvg(set, name) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`missing icon: ${name}`);
  const w = icon.width ?? set.width;
  const h = icon.height ?? set.height;
  const left = icon.left ?? set.left ?? 0;
  const top = icon.top ?? set.top ?? 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${left} ${top} ${w} ${h}">${icon.body}</svg>`;
}

const speciesLines = Object.entries(SPECIES).map(([kind, name]) => {
  const uri = 'data:image/svg+xml;utf8,' + encodeURIComponent(fullSvg(emoji, name));
  return `  ${JSON.stringify(kind)}: ${JSON.stringify(uri)},`;
});

const uiLines = UI.map((name) => {
  const icon = ph.icons[`${name}-duotone`];
  if (!icon) throw new Error(`missing ph icon: ${name}-duotone`);
  const w = icon.width ?? ph.width;
  const h = icon.height ?? ph.height;
  return `  ${JSON.stringify(name)}: { body: ${JSON.stringify(icon.body)}, w: ${w}, h: ${h} },`;
});

const out = `// GENERATED by scripts/gen-art.mjs. Do not edit by hand; run \`npm run art\`.
//
// Licences (both MIT):
//   Fluent Emoji, Microsoft (https://github.com/microsoft/fluentui-emoji/blob/main/LICENSE)
//   Phosphor Icons (https://github.com/phosphor-icons/core/blob/main/LICENSE)

/** Species art, one full-colour data URI per species_kind. Safe in <img> (CSP img-src data:). */
export const SPECIES_ART: Record<string, string> = {
${speciesLines.join('\n')}
};

/** Phosphor duotone icons as raw SVG body. Inline them so fill="currentColor" follows the theme. */
export const ICONS: Record<string, { body: string; w: number; h: number }> = {
${uiLines.join('\n')}
};
`;

writeFileSync(join(root, 'lib/art.ts'), out);
console.log(`wrote lib/art.ts (${out.length} chars): species=${Object.values(SPECIES).join(', ')}; ui=${UI.join(', ')}`);
