// Generates lib/outcodes.ts: every UK postcode district (outward code) with centroid, admin district and region. Run: node scripts/gen-outcodes.mjs
// Source: Postcodes.io (ONS Postcode Directory / OS data, Open Government Licence v3.0). There is no list endpoint, so a UK grid is swept with
// the reverse `/outcodes?lon=&lat=&radius=&limit=100`; any query that returns 100 rows is refined with a finer grid so nothing is cut off.
// Region: English centroids are located in the ONS Regions layer; Scotland/Wales/NI come from Postcodes.io's `country`.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { curlCached, curlCachedSync, inPoly, loadRegions, onsLayer, regionAt, REGION_NAMES, sleep } from './data-util.mjs';

const UK_REGIONS = ['London', 'South East', 'South West', 'East of England', 'West Midlands', 'East Midlands',
  'Yorkshire and The Humber', 'North West', 'North East', 'Scotland', 'Wales', 'Northern Ireland']; // = lib/location.ts; rows store the index
const regions = loadRegions();
// Postcodes.io lists every district an outcode touches (SA1 -> "Neath Port Talbot, Swansea"); prefer the ONS district holding the centroid.
const LAD = 'Local_Authority_Districts_May_2026_Boundaries_UK_BUC';
const lads = JSON.parse(curlCachedSync(onsLayer(LAD), `${LAD}.geojson`)).features.map((f) => ({
  name: Object.entries(f.properties).find(([k]) => /^LAD\d+NM$/.test(k))[1],
  polys: f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates,
}));
const districtOf = (r) => {
  const here = lads.find((l) => l.polys.some((p) => inPoly(p, r.longitude, r.latitude)))?.name;
  return here && (r.admin_district ?? []).includes(here) ? here : (r.admin_district ?? [])[0] ?? here ?? '';
};
const found = new Map();
let calls = 0;

async function query(lat, lon, radius) {
  const u = `https://api.postcodes.io/outcodes?lon=${lon.toFixed(4)}&lat=${lat.toFixed(4)}&limit=100&radius=${radius}`;
  let j;
  for (let t = 0; ; t++) {
    try { j = JSON.parse(await curlCached(u, `oc_${lat.toFixed(4)}_${lon.toFixed(4)}_${radius}.json`)); break; } catch (e) {
      if (t > 3) throw e;
      await sleep(2000 * (t + 1));
    }
  }
  calls++;
  for (const r of j.result ?? []) found.set(r.outcode, r);
  return (j.result ?? []).length;
}
async function pool(jobs, n = 5) {
  let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < jobs.length) await jobs[i++](); }));
}

const STEP = 0.18; // ~20 km: every centroid is within ~14 km of a grid point, inside the 25 km radius
const jobs = [];
for (let lat = 49.85; lat < 60.95; lat += STEP) {
  const dLon = STEP / Math.cos((lat * Math.PI) / 180);
  for (let lon = -8.3; lon < 1.9; lon += dLon) {
    jobs.push(async () => {
      if ((await query(lat, lon, 25000)) < 100) return;
      for (let a = 0; a < 4; a++) for (let b = 0; b < 4; b++) // saturated: 4x4 finer grid, 5 km radius
        await query(lat - STEP / 2 + (a + 0.5) * (STEP / 4), lon - dLon / 2 + (b + 0.5) * (dLon / 4), 5000);
    });
  }
}
console.log(`${jobs.length} grid points`);
await pool(jobs);

const rows = [...found.values()].filter((r) => r.latitude != null).sort((a, b) => a.outcode.localeCompare(b.outcode)).map((r) => {
  const country = r.country ?? [];
  const region = country.length && country.every((c) => c === country[0]) && REGION_NAMES.includes(country[0])
    ? country[0] : regionAt(regions, r.longitude, r.latitude);
  return `${r.outcode}|${r.latitude.toFixed(4)}|${r.longitude.toFixed(4)}|${districtOf(r)}|${UK_REGIONS.indexOf(region)}`;
});
const out = `// Generated by scripts/gen-outcodes.mjs. Do not edit by hand.
// Source: Postcodes.io outcodes (ONS Postcode Directory), Open Government Licence v3.0
// (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/).
// Contains OS data © Crown copyright and database right 2026, Royal Mail data © Royal Mail copyright and database right 2026, National Statistics data © Crown copyright and database right 2026.
import { UK_REGIONS } from './location.ts';

// One row per postcode district: "outcode|lat|lon|admin district|index into UK_REGIONS". Centroids, 4 decimals.
const ROWS = ${JSON.stringify(rows.join('\n'))}.split('\\n');

export interface Outcode { outcode: string; lat: number; lon: number; district: string; region: string }

let table: Map<string, Outcode> | undefined;
const all = () => (table ??= new Map(ROWS.map((r) => {
  const [outcode, lat, lon, district, region] = r.split('|');
  return [outcode, { outcode, lat: +lat, lon: +lon, district, region: UK_REGIONS[+region] }];
})));

export const OUTCODE_COUNT = ROWS.length;

/** "se1 7pb", "SE17PB", "W1A 1AA" or just "EH12" -> that postcode district, or null if it is not a UK district we know. */
export function lookupOutcode(postcode: string): Outcode | null {
  const s = postcode.toUpperCase().replace(/[^A-Z0-9]/g, '');
  const m = /^(\\w{2,4}?)\\d[A-Z]{2}$/.exec(s); // full postcode: the last 3 characters are the inward code
  return all().get(m ? m[1] : s) ?? null;
}
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'outcodes.ts'), out);
console.log(`${rows.length} outcodes from ${calls} calls, ${out.length} bytes`);
