// Generates supabase/seed.sql from supabase/seed.json (the single source of seed data).
import { readFileSync } from 'node:fs';

const seed = JSON.parse(readFileSync(new URL('../supabase/seed.json', import.meta.url)));
const lit = (v) =>
  v === null || v === undefined ? 'null'
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : typeof v === 'object' ? `'${JSON.stringify(v).replaceAll("'", "''")}'`
  : `'${v.replaceAll("'", "''")}'`;
const insert = (table, rows) => {
  const cols = Object.keys(rows[0]);
  return `insert into ${table} (${cols.join(', ')}) values\n` +
    rows.map((r) => `(${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n') + ';\n';
};

const species = seed.species.map(({ cost_items, ...s }) => s);
const items = seed.species.flatMap((s) =>
  s.cost_items.map((c) => ({ species_id: s.id, trigger: null, service: null, senior_multiplier: 1, is_essential: true, ...c })));

console.log('-- GENERATED by scripts/gen-seed.mjs from seed.json. Do not edit by hand.\n');
console.log(insert('species', species));
console.log(insert('cost_items', items));
console.log(insert('regional_multipliers', seed.regional_multipliers));
