// Generates lib/uk-districts.ts: simplified Local Authority District outlines in the SAME projected units as lib/uk-map.ts
// (so both layers line up), plus the data for a point-in-polygon `districtAt`. Run: node scripts/gen-uk-districts.mjs
// Source: ONS Open Geography Portal, "Local Authority Districts (May 2026) Boundaries UK BUC" (ultra-generalised), Open Government Licence v3.0.
// Contains National Statistics and OS data (c) Crown copyright and database right 2026.
// Needs `curl` and, at generation time only, `npx mapshaper` (not a dependency), like gen-uk-map.mjs.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toXY } from '../lib/uk-map.ts';
import { curlCachedSync, inPoly, loadRegions, onsLayer } from './data-util.mjs';

const LAYER = 'Local_Authority_Districts_May_2026_Boundaries_UK_BUC';
const TOLERANCE_M = Number(process.env.TOL ?? 250); // Douglas-Peucker tolerance (mapshaper, topology-preserving)
const MIN_ISLAND_KM2 = 2; // keeps Scilly, Anglesey, Wight, Hebrides, Orkney, Shetland; drops rocks
const DEC = Number(process.env.DEC ?? 1); // decimals in path units (1 unit = 0.01 deg lat = 1.1 km; 1 decimal = 110 m)
const dir = mkdtempSync(join(tmpdir(), 'ukdist-'));
const gj = JSON.parse(curlCachedSync(onsLayer(LAYER), `${LAYER}.geojson`));
const nameKey = Object.keys(gj.features[0].properties).find((k) => /^LAD\d+NM$/.test(k));
const codeKey = nameKey.replace('NM', 'CD');
writeFileSync(join(dir, 'in.geojson'), JSON.stringify({
  type: 'FeatureCollection',
  features: gj.features.map((f) => ({ type: 'Feature', properties: { name: f.properties[nameKey], code: f.properties[codeKey] }, geometry: f.geometry })),
}));
execFileSync('npx', ['--yes', 'mapshaper', join(dir, 'in.geojson'), '-filter-islands', `min-area=${MIN_ISLAND_KM2}km2`,
  '-simplify', 'dp', `interval=${TOLERANCE_M}`, '-o', join(dir, 'out.geojson'), 'format=geojson', 'precision=0.00001'], { stdio: 'ignore' });
const simple = JSON.parse(readFileSync(join(dir, 'out.geojson'), 'utf8')).features;

// Region: Scotland/Wales/NI by ONS code prefix, London boroughs by E09 (a vertex vote put Havering in the East); other English districts by majority of their vertices (lon/lat) inside the ONS regions.
const regions = loadRegions().filter((r) => !['Scotland', 'Wales', 'Northern Ireland'].includes(r.name));
const COUNTRY = { S: 'Scotland', W: 'Wales', N: 'Northern Ireland' };
function regionOf(f) {
  if (COUNTRY[f.properties.code[0]]) return COUNTRY[f.properties.code[0]];
  if (f.properties.code.startsWith('E09')) return 'London';
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const votes = new Map();
  for (const poly of polys) for (const [x, y] of poly[0]) {
    const r = regions.find((g) => g.polys.some((p) => inPoly(p, x, y)));
    if (r) votes.set(r.name, (votes.get(r.name) ?? 0) + 1);
  }
  return [...votes].sort((a, b) => b[1] - a[1])[0][0];
}

// Same projection as uk-map.ts; relative path data from rounded absolute coordinates (no drift); "l" repeats implicitly.
const f10 = 10 ** DEC;
const xy = ([lon, lat]) => { const p = toXY(lat, lon); return [Math.round(p.x * f10) / f10, Math.round(p.y * f10) / f10]; };
const fmt = (n) => String(+n.toFixed(DEC));
function ring(r) {
  const p = r.slice(0, -1).map(xy).filter((q, i, a) => i === 0 || q[0] !== a[i - 1][0] || q[1] !== a[i - 1][1]);
  if (p.length < 3) return '';
  let d = `M${fmt(p[0][0])} ${fmt(p[0][1])}l`, first = true;
  for (let i = 1; i < p.length; i++) for (let j = 0; j < 2; j++) {
    const s = fmt(p[i][j] - p[i - 1][j]);
    d += (first || s.startsWith('-') ? '' : ' ') + s; first = false;
  }
  return d + 'z';
}
const districts = simple.map((f) => {
  if (!f.geometry) throw new Error(`${f.properties.name} lost its geometry`);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const d = polys.map((poly) => poly.map(ring).join('')).join('');
  if (!d) throw new Error(`${f.properties.name} is empty`);
  return { name: f.properties.name, region: regionOf(f), d };
}).sort((a, b) => a.name.localeCompare(b.name));

const out = `// Generated by scripts/gen-uk-districts.mjs. Do not edit by hand.
// Source: ONS Open Geography Portal, Local Authority Districts (May 2026) UK BUC, simplified (${TOLERANCE_M} m).
// Licence: Open Government Licence v3.0 (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/).
// Contains National Statistics and OS data © Crown copyright and database right 2026.
import { toXY } from './uk-map.ts';

/** One entry per Local Authority District. \`d\` is SVG path data in the same units as REGIONS in uk-map.ts (use fill-rule evenodd). \`region\` matches UK_REGIONS. */
export const DISTRICTS: { name: string; region: string; d: string }[] = ${JSON.stringify(districts)};

type Ring = number[]; // flat [x, y, x, y, ...]
let parsed: { name: string; region: string; rings: Ring[]; box: number[][] }[] | undefined;
function parse() {
  return (parsed ??= DISTRICTS.map(({ name, region, d }) => {
    const rings = d.split('M').slice(1).map((s) => {
      const [start, rel] = s.replace('z', '').split('l');
      const [x0, y0] = start.trim().split(' ').map(Number);
      const out: Ring = [x0, y0];
      const n = (rel.match(/-?\\d*\\.?\\d+/g) ?? []).map(Number);
      for (let i = 0; i < n.length; i += 2) out.push(out[i] + n[i], out[i + 1] + n[i + 1]);
      return out;
    });
    const xs = rings.flatMap((r) => r.filter((_, i) => i % 2 === 0)), ys = rings.flatMap((r) => r.filter((_, i) => i % 2 === 1));
    return { name, region, rings, box: [[Math.min(...xs), Math.min(...ys)], [Math.max(...xs), Math.max(...ys)]] };
  }));
}

/** The Local Authority District containing a point (even-odd on the projected rings), or null at sea / outside the UK. Borders are good to about 0.5 km. */
export function districtAt(lat: number, lon: number): { name: string; region: string } | null {
  const { x, y } = toXY(lat, lon);
  for (const { name, region, rings, box } of parse()) {
    if (x < box[0][0] || x > box[1][0] || y < box[0][1] || y > box[1][1]) continue;
    let inside = false;
    for (const r of rings) for (let i = 0, j = r.length - 2; i < r.length; j = i, i += 2)
      if ((r[i + 1] > y) !== (r[j + 1] > y) && x < ((r[j] - r[i]) * (y - r[i + 1])) / (r[j + 1] - r[i + 1]) + r[i]) inside = !inside;
    if (inside) return { name, region };
  }
  return null;
}
`;
const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'uk-districts.ts');
writeFileSync(file, out);
console.log(`${file} ${out.length} bytes, ${districts.length} districts`);
